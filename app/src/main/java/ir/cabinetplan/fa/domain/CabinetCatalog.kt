val WORKSHOP_WIDTH_PRESETS_CM = listOf(40, 50, 60, 80, 90, 100, 120)

fun filterCatalog(category: CabinetCategory?, searchQuery: String): List<CatalogItem> {
    val q = searchQuery.trim()
    return PERSIAN_CABINET_CATALOG.filter { item ->
        val categoryMatch = category == null || item.category == category
        val searchMatch = q.isEmpty() ||
            item.nameFa.contains(q) ||
            item.descriptionFa.contains(q) ||
            item.codeFa.contains(q, ignoreCase = true)
        categoryMatch && searchMatch
    }
}
